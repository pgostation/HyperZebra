    static Sprite get(String tool, boolean cursor) {
        Sprite s = SPRITES.get(cursor ? "Cursor" + tool : tool);
        if(s == null) s = SPRITES.get(tool);
        if(s == null) throw new IllegalArgumentException("Unknown tool: " + tool);
        return s;
    }
    private static void add(String name, int hotX, int hotY, String... rows) {
        SPRITES.put(name, new Sprite(hotX, hotY, rows));
    }
    static final class Sprite {
        final int width, height, hotX, hotY;
        final String[] rows;
        final boolean[][] paper;
        Sprite(int hotX, int hotY, String[] rows) {
            this.rows=rows; width=rows[0].length(); height=rows.length;
            this.hotX=hotX<0 ? width/2 : hotX; this.hotY=hotY<0 ? height/2 : hotY;
            paper=new boolean[height][width];
            // Flood only the exterior. The ink grid itself is never smoothed or expanded.
            boolean[][] exterior=new boolean[height][width];
            java.util.ArrayDeque<Integer> queue=new java.util.ArrayDeque<>();
            for(int y=0;y<height;y++) {
                if(rows[y].length()!=width) throw new IllegalArgumentException("Unequal bitmap rows");
                for(int x=0;x<width;x++) if((x==0||y==0||x==width-1||y==height-1)&&rows[y].charAt(x)=='.') {
                    exterior[y][x]=true; queue.add(y*width+x);
                }
            }
            while(!queue.isEmpty()) {
                int p=queue.remove(), x=p%width, y=p/width;
                for(int[] d:new int[][]{{-1,0},{1,0},{0,-1},{0,1}}) {
                    int nx=x+d[0], ny=y+d[1];
                    if(nx>=0&&nx<width&&ny>=0&&ny<height&&!exterior[ny][nx]&&rows[ny].charAt(nx)=='.') {
                        exterior[ny][nx]=true; queue.add(ny*width+nx);
                    }
                }
            }
            for(int y=0;y<height;y++)for(int x=0;x<width;x++)
                paper[y][x]=rows[y].charAt(x)=='o'||(rows[y].charAt(x)=='.'&&!exterior[y][x]);
        }
    }
