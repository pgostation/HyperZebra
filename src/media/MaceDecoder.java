/**
 * MACE 3:1 decoder, written from the observed behaviour of the real Sound Manager alone (no decoder source was used;
 * see tools/mace). What the observations established:
 * <ul>
 * <li>A packet is 2 bytes, a byte is 3 codes: bits 2-0 (3-bit code, first sample), bits 4-3 (2-bit code, second),
 *     bits 7-5 (3-bit code, third). 3-bit codes 0..3 are positive steps of increasing size, 4..7 the negative mirror;
 *     2-bit codes 0..1 positive, 2..3 negative. Stereo interleaves whole packets per channel.</li>
 * <li>A sample is {@code level + step} clipped to 16 bits and output as its high byte; the level then leaks by 1/8:
 *     {@code level = cur - (cur >> 3)}.</li>
 * <li>The step size adapts through an index: {@code index += T[code] - (index >> 5)}, clamped to 0..6143; the step
 *     table row is {@code (index >> 4) & 127}, so the table repeats three times below the clamp and small codes leave
 *     the index at the top where the steps are smallest.</li>
 * </ul>
 * The tables are fitted, not exact: the decoder tracks the real one to within a few units on natural sounds (mean
 * absolute error about 3/256 of full scale against the probes); bit exactness is not claimed.
 * <p>
 * MACE 6:1 (also from observation only, tools/mace/make_probes4.py): a packet is 1 byte = 3 codes in the opposite
 * order (bits 7-5 first, then bits 4-3, then bits 2-0), each code giving 2 output samples. The same kind of index
 * selects a step; {@code cur = level + step} (16-bit clip) but the level does not leak by a fixed 1/8: it integrates,
 * {@code level = cur - (cur * leak) / 32768}, with a leak amount (0..32768) that falls by 508 for every code whose step
 * has the sign of the level and rises by 315 otherwise (a level of exactly 0 counts as agreeing). Constant codes
 * therefore ramp to full scale while alternating signs damp the level. The two output samples of a code interpolate
 * the halved {@code cur} values: with h = cur/2 and h1, h2 the previous two, {@code h1 + h2 - (h2 - h)/4} and
 * {@code h1 + h + (h2 - h)/4}. This level/leak/interpolation arithmetic reproduces the reference bit for bit on
 * constant-code runs; the index constants and tables are fitted (mean error about 1.5/256 on single-code runs, more
 * on random packets, where a tiny step difference can flip the sign rule and shift the DC offset for a while).
 */
