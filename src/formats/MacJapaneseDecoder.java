	private static final Map<Integer, String> OVERRIDES = buildOverrides();

	private MacJapaneseDecoder() {
	}

	static String decode(byte[] data) {
		return decode(data, 0, data.length);
	}

	static String decode(byte[] data, int offset, int length) {
		return decode(data, offset, length, false);
	}

	/**
	 * Bytes that are no character (a lead byte without its trail, an unassigned pair) are U+FFFD in the plain decoding - and
	 * lost: its callers test for U+FFFD to tell Japanese text from other bytes. Text a 68K external hands to HyperTalk has to
	 * come back to it byte for byte, as HyperCard's byte strings do: UxGetTextValue and UxDraw 1.2 swap every trail byte $C2
	 * (HC J's value() trips over it) for '?' and back around EvalExpr, so 青 ($90 $C2) went out as $90 '?' and came back "??".
	 * With rawBytes each such byte is RAW_BYTES+byte, which MacJapaneseEncoder writes back as that byte.
	 */
	static final char RAW_BYTES = '\uEF00';

	static String decode(byte[] data, int offset, int length, boolean rawBytes) {
		if(offset < 0 || length < 0 || offset > data.length - length) {
			throw new IndexOutOfBoundsException();
		}
		StringBuilder result = new StringBuilder(length);
		int end = offset + length;
		int runStart = offset;
		for(int index = offset; index < end;) {
			int first = data[index] & 0xFF;
			int byteCount = 1;
			int code = first;
			if(isLeadByte(first) && index + 1 < end) {
				int second = data[index + 1] & 0xFF;
				if(isTrailByte(second)) {
					code = (first << 8) | second;
					byteCount = 2;
				}
			}
			String replacement = OVERRIDES.get(code);
			if(replacement==null && byteCount==2) {
				replacement = decodeUserDefinedCharacter(first, data[index + 1] & 0xFF);
			}
			if(replacement != null) {
				if(runStart < index) {
					appendShiftJis(result, data, runStart, index - runStart, rawBytes);
				}
				result.append(replacement);
				runStart = index + byteCount;
			}
			index += byteCount;
		}
		if(runStart < end) {
			appendShiftJis(result, data, runStart, end - runStart, rawBytes);
		}
		return normalizeHorizontalPunctuation(result.toString());
	}

	private static void appendShiftJis(StringBuilder result, byte[] data, int offset, int length, boolean rawBytes) {
		String text = new String(data, offset, length, SHIFT_JIS);
		if(!rawBytes || text.indexOf('\uFFFD') < 0) {result.append(text); return;}
		java.nio.charset.CharsetDecoder decoder = SHIFT_JIS.newDecoder()
			.onMalformedInput(java.nio.charset.CodingErrorAction.REPORT)
			.onUnmappableCharacter(java.nio.charset.CodingErrorAction.REPORT);
		java.nio.ByteBuffer in = java.nio.ByteBuffer.wrap(data, offset, length);
		java.nio.CharBuffer out = java.nio.CharBuffer.allocate(length + 1);
		while(true) {
			java.nio.charset.CoderResult r = decoder.decode(in, out, true);
			out.flip(); result.append(out); out.clear();
			if(r.isError()) {for(int i = 0; i < r.length(); i++) result.append((char)(RAW_BYTES + (in.get() & 0xFF))); continue;}
			if(r.isUnderflow()) break;
		}
		decoder.flush(out); out.flip(); result.append(out);
	}

	/**
	 * HyperCard lays out text horizontally.  Some Apple/Japanese conversion
	 * tables (and a few Linux charset/font combinations) can produce the
	 * Unicode vertical presentation forms for ideographic comma/full stop.
	 * Keep those forms out of the shared text model so the Swing and 68K
	 * renderers behave consistently on every host OS.
	 */
	static String normalizeHorizontalPunctuation(String text) {
		StringBuilder normalized = null;
		for(int i = 0; i < text.length(); i++) {
			char replacement;
			switch(text.charAt(i)) {
				case '\uFE11': replacement = '\u3001'; break; // vertical ideographic comma
				case '\uFE12': replacement = '\u3002'; break; // vertical ideographic full stop
				default:
					if(normalized != null) normalized.append(text.charAt(i));
					continue;
			}
			if(normalized == null) {
				normalized = new StringBuilder(text.length());
				normalized.append(text, 0, i);
			}
			normalized.append(replacement);
		}
		return normalized == null ? text : normalized.toString();
	}

	private static String decodeUserDefinedCharacter(int lead, int trail) {
		if(lead < 0xF0 || lead > 0xFC) return null;
		int trailIndex;
		if(trail >= 0x40 && trail <= 0x7E) {
			trailIndex = trail - 0x40;
		} else if(trail >= 0x80 && trail <= 0xFC) {
			trailIndex = 63 + trail - 0x80;
		} else {
			return null;
		}
		return Character.toString((char)(0xE000 + (lead - 0xF0) * 188 + trailIndex));
	}

	private static boolean isLeadByte(int value) {
		return value >= 0x81 && value <= 0x9F || value >= 0xE0 && value <= 0xFC;
	}

	private static boolean isTrailByte(int value) {
		return value >= 0x40 && value <= 0x7E || value >= 0x80 && value <= 0xFC;
	}

	private static Map<Integer, String> buildOverrides() {
		Map<Integer, String> overrides = new HashMap<Integer, String>();
		for(int index = 0; index < OVERRIDE_DATA.length;) {
			int code = OVERRIDE_DATA[index++];
			int count = OVERRIDE_DATA[index++];
			StringBuilder value = new StringBuilder(count);
			for(int i = 0; i < count; i++) {
				value.appendCodePoint(OVERRIDE_DATA[index++]);
			}
			overrides.put(code, value.toString());
		}
		return overrides;
	}
